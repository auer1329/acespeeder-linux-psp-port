/* The course model (original global at 0x44c230) and the per-course data files
 * produced by re/scripts/extract_tracks.py. The struct keeps the original memory
 * layout so code translated from the decompilation can use the same indexing. */
#ifndef TRACK_H
#define TRACK_H

#include <stdint.h>

#include "../engine/rm.h"
#include "gmath.h"
#include "machine.h"

#define TRACK_MAX_POINTS 30

typedef struct {
	int16_t n;              /* 0x0000 last control point index (segments = n+1) */
	int16_t pad0;
	float px[30];           /* 0x0004 segment end points (mid points of controls) */
	float py[30];           /* 0x007c */
	float pz[30];           /* 0x00f4 */
	float cx[30];           /* 0x016c control points */
	float cy[30];           /* 0x01e4 */
	float cz[30];           /* 0x025c */
	float bank[30];         /* 0x02d4 roll at segment ends */
	float cbank[30];        /* 0x034c roll at control points */
	float ax[240];          /* 0x03c4 cross-section at segment start, x [seg*8+k] */
	float bx[240];          /* 0x0784 cross-section at segment end, x */
	float ay[240];          /* 0x0b44 */
	float by[240];          /* 0x0f04 */
	int16_t ptype[30];      /* 0x12c4 cross-section profile id */
	int16_t edge[240];      /* 0x1300 surface type per edge */
	float seglen[30];       /* 0x14e0 */
	int16_t chg_start[30];  /* 0x1558 profile differs from previous segment */
	int16_t chg_end[30];    /* 0x1594 profile differs from next segment */
	float f15d0;            /* 0x15d0 start position (track units) */
	float f15d4;            /* 0x15d4 */
	Vec3 center[30];        /* 0x15d8 segment centres (culling) */
	float radius[30];       /* 0x1740 segment bounding radius */
	int16_t nscenery;       /* 0x17b8 */
	int16_t pad2;
	float scen[0x96];       /* 0x17bc random scenery bands */
	int16_t laps;           /* 0x1a14 */
	int16_t pad3;
	double reftime;         /* 0x1a18 */
	int16_t env;            /* 0x1a20 scenery set 0..2: course/sky/ground<env+1> */
	int16_t s1a22;          /* 0x1a22 */
	int16_t s1a24;          /* 0x1a24 */
	int16_t pad4;
} Track;

extern Track g_track;

/* Geometry of one segment as generated by the original's Track_BuildMeshes. */
typedef struct {
	Vec3 pos;               /* frame position relative to the scene */
	uint32_t quality;
	RMMeshBuilder *mb;
} TrackSegment;

typedef struct {
	int nseg;
	TrackSegment seg[TRACK_MAX_POINTS];
	RMTexture *tex; /* course<env+1>.bmp */
} TrackMeshes;

/* Loads track_<stage>_<course>.bin (1-based numbers): fills g_track, g_pickups
 * and creates one mesh builder per segment. */
int Track_Load(int stage, int course, TrackMeshes *out);
void Track_FreeMeshes(TrackMeshes *m);

Vec3 Track_Point(const Track *trk, TrackPos p);  /* 0x4078a0 */
Mat3 Track_Frame(const Track *trk, TrackPos p);  /* 0x407c30 */

#endif
