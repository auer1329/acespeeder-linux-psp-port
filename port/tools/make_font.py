#!/usr/bin/env python3
"""Generate src/engine/font_data.h: a 2-bit glyph table replacing the GDI
"MS Gothic" text of the original. Covers ASCII plus every character that
appears in the executable's Shift-JIS strings. Glyphs are rendered with
DejaVu Sans Mono (Latin) and Droid Sans Fallback (Japanese).

Usage: make_font.py ../game/AceSpeeder.exe > src/engine/font_data.h"""
import re
import sys

from PIL import Image, ImageDraw, ImageFont

CELL = 32  # glyph height; half-width glyphs are CELL/2 wide, full-width CELL
LATIN = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
CJK = "/usr/share/fonts/truetype/droid/DroidSansFallbackFull.ttf"


def data_sections(path):
    import struct
    data = open(path, "rb").read()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    nsec = struct.unpack_from("<H", data, pe + 6)[0]
    opt = struct.unpack_from("<H", data, pe + 20)[0]
    for i in range(nsec):
        o = pe + 24 + opt + 40 * i
        name = data[o:o + 8].rstrip(b"\0")
        size, off = struct.unpack_from("<II", data, o + 16)
        if name in (b".data", b".rdata"):
            yield data[off:off + size]


def exe_chars(path):
    chars = set()
    # NUL-delimited strings of printable Shift-JIS (ASCII or double-byte)
    for data in data_sections(path):
        chars |= strings_chars(data)
    return chars


def strings_chars(data):
    chars = set()
    # a single character counts only when double-byte (the password letters Ａ..Ｆ
    # and the cursor ￣ are stored one per string)
    for m in re.finditer(rb"(?<=\0)(?:(?:[\x20-\x7e]|[\x81-\x9f\xe0-\xfc][\x40-\xfc]){2,}"
                         rb"|[\x81-\x9f\xe0-\xfc][\x40-\xfc])(?=\0)", data):
        try:
            s = m.group().decode("cp932")
        except UnicodeDecodeError:
            continue
        if any(ord(c) > 0x7f for c in s):
            chars.update(c for c in s if ord(c) > 0x7f)
    return chars


def render(ch, font, w):
    img = Image.new("L", (w, CELL), 0)
    d = ImageDraw.Draw(img)
    box = d.textbbox((0, 0), ch, font=font)
    x = (w - (box[2] - box[0])) // 2 - box[0]
    d.text((x, 2), ch, font=font, fill=255)
    return img


def main():
    latin = ImageFont.truetype(LATIN, 26)
    cjk = ImageFont.truetype(CJK, 28)
    chars = [chr(c) for c in range(0x20, 0x7f)] + sorted(exe_chars(sys.argv[1]))
    glyphs, bits = [], bytearray()
    for ch in chars:
        wide = ord(ch) > 0x7f and not (0xff61 <= ord(ch) <= 0xff9f)
        w = CELL if wide else CELL // 2
        img = render(ch, cjk if wide else latin, w)
        glyphs.append((ord(ch), w, len(bits)))
        px = list(img.tobytes())
        for i in range(0, len(px), 4):
            b = 0
            for k in range(4):
                b |= (px[i + k] >> 6) << (2 * k)
            bits.append(b)
    out = ["/* Generated by tools/make_font.py -- do not edit. */",
           f"#define FONT_CELL {CELL}", f"#define FONT_NGLYPHS {len(glyphs)}",
           "static const struct { unsigned code; unsigned char w; unsigned offset; } font_glyphs[] = {"]
    out += [f"\t{{0x{c:x}, {w}, {o}}}," for c, w, o in glyphs]
    out.append("};")
    out.append("static const unsigned char font_bits[] = {")
    for i in range(0, len(bits), 24):
        out.append("\t" + ",".join(str(b) for b in bits[i:i + 24]) + ",")
    out.append("};")
    print("\n".join(out))
    print(f"{len(glyphs)} glyphs, {len(bits)} bytes", file=sys.stderr)


if __name__ == "__main__":
    main()
