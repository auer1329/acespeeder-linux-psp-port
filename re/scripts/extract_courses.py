#!/usr/bin/env python3
"""Run the 36 course-definition functions of AceSpeeder.exe under emulation and
write their results as C tables (port/src/game/course_data.c).

Each function fills part of the global Track (0x44c230) and the pickup list
(0x451f78) from hard-coded constants; emulating them gives the exact values
without hand-transcribing ~5000 lines of decompiled code.
"""
import struct
from pathlib import Path

from emu import Emu

# Order of Course_BuildTrack's switch: [stage][course]
COURSE_FUNCS = [
    [0x424b10, 0x425380, 0x425ea0, 0x426a60, 0x4272b0, 0x427e60],
    [0x428880, 0x429170, 0x429e70, 0x42aad0, 0x42b5d0, 0x42bfc0],
    [0x42c860, 0x42d350, 0x42de50, 0x42ea90, 0x42f4e0, 0x42ff80],
    [0x430a30, 0x431820, 0x4321f0, 0x433120, 0x433c50, 0x434780],
    [0x435000, 0x4359f0, 0x436490, 0x436de0, 0x437750, 0x4386a0],
    [0x439260, 0x4399e0, 0x43a6b0, 0x43b0f0, 0x43bd90, 0x43ca80],
]

TRACK = 0x44C230
TRACK_HEAD = 0x15D8   # n .. f15d4: everything the course functions write up to the centres
TRACK_TAIL = (0x1A14, 0x1A28)  # laps, f1a18, f1a1c, s1a20, s1a22, s1a24 (+pad)
PICKUPS = 0x451F78
PICKUPS_SIZE = 0x600

OUT = Path(__file__).resolve().parent.parent.parent / "port" / "src" / "game" / "course_data.c"


def check_dispatcher(e):
    """Make sure the table above matches the binary's switch (by disassembly of call targets)."""
    import re
    src = (Path(__file__).resolve().parent.parent / "decomp").glob("00418530_*.c")
    text = next(src).read_text()
    found = [int(x, 16) for x in re.findall(r"FUN_00([0-9a-f]{6})\(\)", text)]
    flat = [f for row in COURSE_FUNCS for f in row]
    assert found == flat, f"dispatcher mismatch: {[hex(x) for x in found]}"


def words(b):
    return struct.unpack(f"<{len(b) // 4}I", b)


def main():
    check_dispatcher(None)
    lines = [
        "/* Generated by re/scripts/extract_courses.py from AceSpeeder.exe -- do not edit.",
        " * Raw images of the Track (0x44c230) head/tail and of the pickup list (0x451f78)",
        " * as the original's 36 course functions leave them. */",
        "#include \"course_data.h\"",
        "",
        "const CourseImage k_course_images[6][6] = {",
    ]
    for s, row in enumerate(COURSE_FUNCS):
        lines.append("\t{")
        for c, fn in enumerate(row):
            e = Emu()
            e.call(fn)
            head = e.read(TRACK, TRACK_HEAD)
            tail = e.read(TRACK + TRACK_TAIL[0], TRACK_TAIL[1] - TRACK_TAIL[0])
            pick = e.read(PICKUPS, PICKUPS_SIZE)
            n = struct.unpack_from("<h", head)[0]
            npick = struct.unpack_from("<h", pick)[0]
            lines.append(f"\t\t{{ /* stage {s + 1} course {c + 1}: FUN_{fn:08x}, {n + 1} control points, "
                         f"{npick} pickups */")
            for name, blob in (("head", head), ("tail", tail), ("pickups", pick)):
                w = words(blob)
                lines.append(f"\t\t\t.{name} = {{")
                for i in range(0, len(w), 8):
                    lines.append("\t\t\t\t" + ", ".join(f"0x{x:08x}" for x in w[i:i + 8]) + ",")
                lines.append("\t\t\t},")
            lines.append("\t\t},")
        lines.append("\t},")
    lines.append("};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
