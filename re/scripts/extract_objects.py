#!/usr/bin/env python3
"""Run the 36 course-object functions of AceSpeeder.exe (called from Race_Setup)
under emulation and write the gates and buildings they place as C tables
(port/src/game/course_objects.c).

Each function only calls Gates_Add (0x40e2a0) and Buildings_Add (0x40de80) with
constants, plus helpers that set fog on the created frames; the adders are
stubbed so their arguments can be recorded.
"""
import re
import struct
from pathlib import Path

from emu import Emu

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT.parent / "port" / "src" / "game" / "course_objects.c"

GATES_ADD = 0x40E2A0      # thiscall (kind, s, mode, speed, sx, sy, sz)
BUILDINGS_ADD = 0x40DE80  # thiscall (kind, s, side, yaw, sx, sy, sz)
GATES_FOG = 0x40E450
BUILDINGS_FOG = 0x40E0D0


def object_funcs():
    """The [stage][course] switch of Race_Setup, in order."""
    text = next((ROOT / "decomp").glob("00417070_*.c")).read_text()
    part = text[text.index("Doors_Init"):text.index("switch(DAT_00451702)")]
    found = [int(x, 16) for x in re.findall(r"FUN_00([0-9a-f]{6})\(\)", part)]
    assert len(found) == 36, len(found)
    return [found[i * 6:i * 6 + 6] for i in range(6)]


def f32(w):
    return struct.unpack("<f", struct.pack("<I", w))[0]


def cf(x):
    """Shortest decimal that rounds back to the same float32."""
    for prec in range(1, 12):
        s = f"{x:.{prec}f}"
        if struct.unpack("<f", struct.pack("<f", float(s)))[0] == x:
            break
    return (s if "." in s or "e" in s else s + ".0") + "f"


def main():
    funcs = object_funcs()
    lines = [
        "/* Generated by re/scripts/extract_objects.py from AceSpeeder.exe -- do not edit.",
        " * Gates and buildings placed by the 36 course-object functions that Race_Setup calls. */",
        "#include \"course_objects.h\"",
        "",
        "const CourseObjects k_course_objects[6][6] = {",
    ]
    for s, row in enumerate(funcs):
        lines.append("\t{")
        for c, fn in enumerate(row):
            e = Emu()
            for a in (GATES_ADD, BUILDINGS_ADD):
                e.stub(a, 7, conv="thiscall")
            for a in (GATES_FOG, BUILDINGS_FOG):
                e.stub(a, 0, conv="thiscall", record=False)
            e.call(fn)
            gates = [(g[0], f32(g[1]), g[2] & 0xFFFF, f32(g[3]), f32(g[4]), f32(g[5]), f32(g[6]))
                     for a, _, g in e.calls if a == GATES_ADD]
            builds = [(g[0], f32(g[1]), f32(g[2]), f32(g[3]), f32(g[4]), f32(g[5]), f32(g[6]))
                      for a, _, g in e.calls if a == BUILDINGS_ADD]
            assert len(gates) <= 16 and len(builds) <= 24
            lines.append(f"\t\t{{ /* {s + 1}-{c + 1}: {fn:#x} */")
            lines.append(f"\t\t\t{len(gates)}, {{")
            for g in gates:
                lines.append(f"\t\t\t\t{{{g[0]}, {cf(g[1])}, {g[2]}, {cf(g[3])}, {{{cf(g[4])}, {cf(g[5])}, {cf(g[6])}}}}},")
            lines.append("\t\t\t},")
            lines.append(f"\t\t\t{len(builds)}, {{")
            for b in builds:
                lines.append(f"\t\t\t\t{{{b[0]}, {cf(b[1])}, {cf(b[2])}, {cf(b[3])}, {{{cf(b[4])}, {cf(b[5])}, {cf(b[6])}}}}},")
            lines.append("\t\t\t},")
            lines.append("\t\t},")
        lines.append("\t},")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
